// Sync the dashboard topology module, styles and icons into site/ so the product
// page reuses the real module. Run `npm run site:sync` after touching the dashboard
// copy; `npm run site:check` verifies the committed files are still in sync.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DASHBOARD_ASSET_PREFIX = '/dashboard/assets/topology/';
const SITE_ASSET_PREFIX = 'assets/topology/';
const GENERATED_HEADER = '// GENERATED by scripts/sync-site.js from src/dashboard/topology.js — do not edit';

// [relative path, expected content (string or Buffer)]
function targets() {
  const files = [];
  const source = readFileSync(join(root, 'src/dashboard/topology.js'), 'utf8');
  const occurrences = source.split(DASHBOARD_ASSET_PREFIX).length - 1;
  if (occurrences !== 1) {
    console.error(`expected exactly 1 occurrence of ${DASHBOARD_ASSET_PREFIX} in src/dashboard/topology.js, found ${occurrences}`);
    process.exit(1);
  }
  files.push(['site/vendor/topology.js', `${GENERATED_HEADER}\n${source.replaceAll(DASHBOARD_ASSET_PREFIX, SITE_ASSET_PREFIX)}`]);
  files.push(['site/vendor/topology.css', readFileSync(join(root, 'src/dashboard/topology.css'))]);
  for (const name of readdirSync(join(root, 'src/dashboard/topology-assets')).sort()) {
    if (!name.endsWith('.png')) continue;
    const content = readFileSync(join(root, 'src/dashboard/topology-assets', name));
    files.push([`site/assets/topology/${name}`, content]);
    if (name === 'gateway.png') files.push(['site/assets/icon.png', content]);
  }
  return files;
}

const check = process.argv.includes('--check');
let mismatched = 0;
for (const [relative, expected] of targets()) {
  const path = join(root, relative);
  let onDisk = null;
  try { onDisk = readFileSync(path); } catch { /* treated as missing */ }
  const inSync = onDisk !== null
    && (typeof expected === 'string' ? onDisk.toString() === expected : onDisk.equals(expected));
  if (check) {
    if (!inSync) { console.log(`DIFF ${relative}`); mismatched++; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, expected);
    console.log(`wrote ${relative}`);
  }
}
if (check && mismatched) {
  console.error(`${mismatched} file(s) out of sync — run: npm run site:sync`);
  process.exit(1);
}
